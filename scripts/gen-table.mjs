// CSV(소스 진실)를 빌드 타임에 TS 모듈로 임베드한다.
// JSON import는 Next 서버 빌드에서 에셋 파일로 외부화될 수 있고(→ 워커 런타임 fs 불가로 빈 테이블),
// TS 소스의 배열 리터럴은 webpack이 외부화하지 못해 항상 JS 번들에 인라인된다.
// build / cf:build 가 매번 재생성 → CSV-데이터 드리프트 없음.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "csv-parse/sync";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSV = path.join(root, "data", "전결_검색테이블_통합.csv");
const TS_OUT = path.join(root, "lib", "tableData.generated.ts");

const csv = fs.readFileSync(CSV, "utf-8");
const rows = parse(csv, { columns: true, skip_empty_lines: true, bom: true });

// 각 줄의 원문행이 전체 원문에 있고 결재 표시(★○)와 맞는지 확인한다. 어긋나면 빌드를 멈춘다.
// 판단구분: 원문(★○ 그대로) · 해석(원문에 없는 업무, 적힌 행 준용) · 단독전결(원문은 ○만) · 셀 내 조건(원문 칸 글 속 예외라 ★○ 대조 생략)
const FULL = path.join(root, "lib", "fullData.generated.ts");
const fullSrc = fs.readFileSync(FULL, "utf-8");
const records = new Map(JSON.parse(fullSrc.slice(fullSrc.indexOf("["), fullSrc.lastIndexOf("]") + 1)).map((r) => [r.id, r]));
const rank = (v) => v.replace(/[\s·∙]/g, "");
const ranks = (list) => list.map(rank).sort().join(",");
const errors = [];
rows.forEach((row, i) => {
  const at = `CSV ${i + 2}행(${row["검색키"]} ${row["분기조건"]})`;
  const record = records.get(row["원문행"]);
  if (!record) return errors.push(`${at}: 원문행 '${row["원문행"]}'이 전체 원문에 없음`);
  const basis = row["판단구분"];
  const approverOk = rank(row["전결권자"]) === ranks(record.approver);
  const drafterOk = ranks(row["기안권자"].split(",")) === ranks(record.drafter);
  if (basis === "원문" || basis === "해석") {
    if (!approverOk || !drafterOk) errors.push(`${at}: ★○ 불일치 (원문 ${record.drafter.join(",")}→${record.approver.join(",")})`);
  } else if (basis === "단독전결") {
    if (!approverOk || record.drafter.length) errors.push(`${at}: 단독전결인데 원문 ★○가 다름`);
  } else if (basis !== "셀 내 조건") {
    errors.push(`${at}: 판단구분 '${basis}'을 알 수 없음`);
  }
});
if (errors.length) {
  console.error(`gen-table: 원문 대조 실패 ${errors.length}건\n${errors.join("\n")}`);
  process.exit(1);
}

const banner =
  "// AUTO-GENERATED by scripts/gen-table.mjs — do not edit.\n" +
  "// Source: data/전결_검색테이블_통합.csv (수정 시 `npm run data:build`)\n";
const body =
  "const rows: Record<string, string>[] = " +
  JSON.stringify(rows) +
  ";\nexport default rows;\n";
fs.writeFileSync(TS_OUT, banner + body, "utf-8");
console.log(`gen-table: ${rows.length}행 → ${path.relative(root, TS_OUT)}`);
