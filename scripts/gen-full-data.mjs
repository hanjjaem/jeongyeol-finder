import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// 원문 정규화 JSON의 원본은 빅데이터플랫폼 운영 폴더에 있다(엑셀 → normalize_workbook.py → records.json).
// 로컬 전용 명령이며 CI 빌드는 커밋된 생성물만 사용한다.
const DEFAULT_INPUT = "D:\\00.hjr\\빅데이터플랫폼\\2026\\운영\\services\\jeongyeol-finder\\data\\normalized\\records.json";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const inputFlag = args.indexOf("--input");
const input = inputFlag >= 0 ? args[inputFlag + 1] : DEFAULT_INPUT;
const output = path.join(root, "lib", "fullData.generated.ts");
const departmentsOutput = path.join(root, "lib", "fullDepartments.generated.ts");

if (!input) throw new Error("--input 경로가 필요합니다");
const document = JSON.parse(fs.readFileSync(input, "utf-8"));
if (!Array.isArray(document.records) || document.records.length === 0) {
  throw new Error("정규화 문서에 records 배열이 없습니다");
}

// --check: 생성물이 원본 records.json과 같은 버전인지 확인만 한다(파일을 쓰지 않음).
if (args.includes("--check")) {
  const current = fs.readFileSync(output, "utf-8").match(/^\/\/ Source hash: (\w+)/m)?.[1];
  if (current !== document.source_version) {
    console.error(`data:check 실패: 생성물 ${current} ≠ 원본 ${document.source_version}\n→ npm run data:full 후 테스트·빌드하세요.`);
    process.exit(1);
  }
  console.log(`data:check 통과: ${document.source_version}`);
  process.exit(0);
}

const banner =
  "// AUTO-GENERATED by scripts/gen-full-data.mjs — do not edit.\n" +
  `// Source hash: ${document.source_version}\n`;
const body = `const rows = ${JSON.stringify(document.records)};\nexport default rows;\n`;
fs.writeFileSync(output, banner + body, "utf-8");

// 첫 화면의 부서 선택 목록은 전체 원문(2MB+)을 불러오지 않도록 별도 파일로 둔다.
const departments = [...new Set(document.records.map((record) => record.department_scope))];
fs.writeFileSync(departmentsOutput, banner + `const departments: string[] = ${JSON.stringify(departments)};\nexport default departments;\n`, "utf-8");
console.log(`gen-full-data: ${document.records.length}행·${departments.length}개 부서 → ${path.relative(root, output)}`);
